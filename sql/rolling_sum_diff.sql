with cte as (
  select
    txn_date,
    sum(amount) as amount
  from 
    transactions
  group by 
    txn_date
  order by 
    txn_date

),
rolling as (
select 
  txn_date,
  amount as daily_revenue,
  sum(amount) over(order by txn_date range between interval '29' day preceding and current row) as rolling_30_days
from 
  cte
)
select
*,
round(100 * (rolling_30_days - lag(rolling_30_days) over(order by txn_date)) * 1.0 / (lag(rolling_30_days) over(order by txn_date)), 2) as pct
from rolling;

